import colorama
from concurrent.futures import ThreadPoolExecutor, as_completed
GREEN = colorama.Fore.GREEN
RED = colorama.Fore.RED
STRANGE = colorama.Fore.LIGHTBLACK_EX
fcl = colorama.Fore.RESET
fch = colorama.Fore.MAGENTA
def check_social(name, url):
    try: 
        response = httpx.get(url, timeout=7, follow_redirects=True, headers={"user-agent": "mozilla/5.0"})
        if response.status_code == 200: return name, url, response.status_code, "fnd"
        elif response.status_code == 404: return name, url, response.status_code, "nf"
        else: return name, url, response.status_code, "othr"
    except Exception: pass
    try:
        response = requests.get(url, timeout=7, allow_redirects=True, headers={"user-agent": "mozilla/5.0"})
        if response.status_code == 200: return name, url, response.status_code, "fnd"
        elif response.status_code == 404: return name, url, response.status_code, "nf"
        else: return name, url, response.status_code, "othr"
    except Exception: return name, url, None, "err"
def scan_socials(socials, workers=30):
    found = []
    print(f"проверяю {len(socials)} сйтв")
    with ThreadPoolExecutor(max_workers=workers) as executor:
        futures = {
            executor.submit(check_social, name, url): name
            for name, url in socials.items()
        }
        for future in as_completed(futures):
            try: name, url, status, result = future.result()
            except Exception as e:
                print(f"{RED}ошибка потока {e}{fcl}")
                continue
            if result == "fnd":
                print(f"{GREEN}[+]{fcl}{fch} {name}: {url}{fcl}")
                found.append({"name": name, "url": url, "status": status})
            elif result == "nf": print(f"{RED}[-]{fch} {name}: 404 не найдено{fcl}")
            elif result == "err": print(f"{STRANGE}[?]{fch} {name}: ошибка соединения{fcl}")
            else:print(f"{STRANGE}[?]{fch} {name}: http {status}{fcl}")
    return found
